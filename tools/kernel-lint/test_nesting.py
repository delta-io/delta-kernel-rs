"""Verify that nesting metrics use Rust AST scopes rather than indentation or braces."""

import os
from pathlib import Path
import shutil
import tempfile
import unittest

from nesting import measure


@unittest.skipUnless(shutil.which(os.environ.get("AST_GREP", "ast-grep")), "ast-grep is required")
class NestingTests(unittest.TestCase):
    def measure_source(self, source):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "source.rs").write_text(source)
            return measure(root, ["source.rs"])["functions"]

    def test_outer_scopes_and_string_braces_do_not_inflate_depth(self):
        rows = self.measure_source('mod m { impl T { fn f() { let text = "{{{{"; if a { if b {} } } } }')
        self.assertEqual([(row["name"], row["bodyMaxDepth"]) for row in rows], [("f", 2)])

    def test_nested_functions_are_measured_separately_and_closures_count(self):
        rows = self.measure_source('fn outer() { fn inner() { if a { if b {} } } } fn callback() { call(|| { if a {} }); }')
        self.assertEqual([(row["name"], row["bodyMaxDepth"]) for row in rows],
                         [("outer", 0), ("inner", 2), ("callback", 2)])

    def test_match_arm_blocks_count_and_generated_sources_are_excluded(self):
        rows = self.measure_source('fn f() { match x { X => { if a {} }, _ => {} } }')
        self.assertEqual(rows[0]["bodyMaxDepth"], 3)
        self.assertEqual(self.measure_source('//! Generated by a test\nfn f() { if a {} }'), [])
        rows = self.measure_source('//! Generated columns: top-level columns\nfn f() { if a {} }')
        self.assertEqual(rows[0]["bodyMaxDepth"], 1)

    def test_duplicate_and_overlapping_paths_do_not_duplicate_scopes(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "source.rs").write_text("fn f() { if a {} }")
            expected = measure(root, ["source.rs"])
            self.assertEqual(measure(root, ["source.rs", "source.rs"]), expected)
            self.assertEqual(measure(root, [".", "source.rs"]), expected)


if __name__ == "__main__":
    unittest.main()
